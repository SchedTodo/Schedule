import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const generatedDirectory = resolve('src/parser/generated')
const generatedFiles = (await readdir(generatedDirectory)).filter((file) => file.endsWith('.ts'))
const marker = '// @ts-nocheck -- generated by ANTLR 4.13.2\n'
const runtimeMissingTypes = ['DecisionState', 'TokenStream']

await Promise.all(
  generatedFiles.map(async (file) => {
    const path = resolve(generatedDirectory, file)
    const source = await readFile(path, 'utf8')
    let body = source.startsWith(marker) ? source.slice(marker.length) : source
    body = body.replace(/^import type \{ (?:DecisionState|TokenStream)(?:, (?:DecisionState|TokenStream))* \} from 'antlr4';?\r?\n/mu, '')
    const runtimeImportPattern = /import \{[\s\S]*?\} from ['"]antlr4['"];/u
    const runtimeImport = body.match(runtimeImportPattern)?.[0]
    const typeImports = runtimeMissingTypes.filter((name) => runtimeImport?.includes(name))
    if (runtimeImport !== undefined && typeImports.length > 0) {
      const correctedImport = typeImports.reduce(
        (value, name) => value.replace(new RegExp(`\\s*${name},?`, 'u'), ''),
        runtimeImport
      )
      body = body.replace(runtimeImport, correctedImport)
      body = `import type { ${typeImports.join(', ')} } from 'antlr4'\n${body}`
    }
    await writeFile(path, `${marker}${body}`, 'utf8')
  })
)
